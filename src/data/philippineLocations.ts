/**
 * Get available barangays for a given city.
 */
export function getBarangaysForCity(city: string): string[] {
  if (!city) return [];
  const map = CITY_BARANGAY_POSTAL_CODES[city];
  if (map) {
    return Object.keys(map);
  }
  return [];
}

/**
 * Determine postal code by city and barangay.
 * If barangay is specified and found, returns that specific postal code.
 * If not found, falls back to the city default postal code.
 */
export function determinePostalCode(city: string, barangay: string): string {
  if (!city) return '';
  const map = CITY_BARANGAY_POSTAL_CODES[city];
  if (map && barangay && map[barangay]) {
    return map[barangay];
  }
  // Try case-insensitive or partial match
  if (map && barangay) {
    const target = barangay.trim().toLowerCase();
    for (const [key, code] of Object.entries(map)) {
      if (key.toLowerCase() === target || key.toLowerCase().includes(target)) {
        return code;
      }
    }
  }
  return CITY_DEFAULT_POSTAL_CODES[city] || '';
}
